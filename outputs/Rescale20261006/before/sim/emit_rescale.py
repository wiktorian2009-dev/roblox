def nice(x, n=2):
    if x < 100: return int(round(x))
    e = 10 ** (math.floor(math.log10(x)) - (n - 1))
    return int(round(x / e)) * e

def abbrev(x):
    for s, v in (("T", 1e12), ("B", 1e9), ("M", 1e6), ("K", 1e3)):
        if x >= v: return ("%g" % float("%.3g" % (x / v))) + s
    return "%d" % x

def snow_map(new):
    """old-scale Snow amount -> equivalent new-scale amount: identity up to the Desert gate, then log-linear between matching gates"""
    pts = [(OLD[s], new[s]) for s in ORDER]
    def m(x):
        x = float(x)
        if x <= pts[0][0]: return x
        for (a0, b0), (a1, b1) in zip(pts, pts[1:]):
            if x <= a1:
                f = math.log(x / a0) / math.log(a1 / a0)
                return b0 * (b1 / b0) ** f
        (a0, b0), (a1, b1) = pts[-2], pts[-1]
        k = math.log(b1 / b0) / math.log(a1 / a0)
        return b1 * (x / a1) ** k
    return m, pts

def sub_cost(src, ident, value, note):
    pat = re.compile(r'(\{Id = "%s",[^\n]*?Cost = )([0-9.e+]+)' % re.escape(ident))
    mo = pat.search(src)
    assert mo, ident
    return src[:mo.start(2)] + ("%d" % value if value < 1e15 else "%.6g" % value) + src[mo.end(2):]

MIGRATION = r'''-- EconomyMigration (2026-10-06, Claude; generated by outputs/Rebalance20261005/sim/emit_rescale.py - edit there and regenerate).
-- The economy was rescaled (nothing above the trillions). Profiles saved before that hold Snow on the OLD scale; this converts them
-- ONCE (d.EconomyVersion) to the equivalent progress on the new scale, without resetting anything:
--   * Snow balance, lifetime Snow (achievements / quests) and the recent Snow/s used by SnowMinutes rewards are mapped through the
--     stage gates: an amount that was X% of the way from one old gate to the next is X% (in log terms) between the new gates.
--     Amounts below the Desert gate are unchanged (the start of the game kept its prices).
--   * "Dig X snow" quests keep their progress fraction; stored part offers and the reservation are re-priced with C.OfferPrice
--     (the lower of the stored and the current catalog price). Parts, pets, stages, rebirths, upgrades and settings are untouched.
-- New profiles start at the current version and are never converted. Running Apply twice changes nothing the second time.
local M = {}
M.VERSION = 2
M.PAIRS = { -- {old-scale gate, new-scale gate}, in stage order (Desert ... Cosmic)
%PAIRS%
}
local P = M.PAIRS
function M.Map(x)
	x = tonumber(x) or 0
	if x ~= x or x == math.huge then return 0 end
	if x <= P[1][1] then return x end
	for i = 1, #P - 1 do
		local a0, b0, a1, b1 = P[i][1], P[i][2], P[i + 1][1], P[i + 1][2]
		if x <= a1 then
			local f = math.log(x / a0) / math.log(a1 / a0)
			return b0 * (b1 / b0) ^ f
		end
	end
	local a0, b0, a1, b1 = P[#P - 1][1], P[#P - 1][2], P[#P][1], P[#P][2]
	return b1 * (x / a1) ^ (math.log(b1 / b0) / math.log(a1 / a0))
end
local function factor(x) -- local scale factor new/old around amount x
	if x <= 0 then return 1 end
	return M.Map(x) / x
end
function M.Apply(d, config)
	if type(d) ~= "table" then return false end
	if (tonumber(d.EconomyVersion) or 1) >= M.VERSION then return false end
	local before = {Snow = tonumber(d.Snow) or 0, SnowEarned = tonumber(d.SnowEarned) or 0}
	d.Snow = math.floor(M.Map(math.max(0, before.Snow)) + 0.5)
	local oldEarned = math.max(0, before.SnowEarned)
	d.SnowEarned = math.floor(M.Map(oldEarned) + 0.5)
	local a = type(d.Activity) == "table" and d.Activity or nil
	if a then
		local r = tonumber(a.Rate) or 0
		if r > 0 and r == r and r ~= math.huge then a.Rate = r * factor(r * 600) end -- ~10 minutes of digging sets the scale
		if type(a.Quests) == "table" then
			local f = factor(math.max(oldEarned, 1))
			for _, q in pairs(a.Quests) do
				if type(q) == "table" and q.Id == "Dig" and tonumber(q.Goal) then
					local done = math.max(0, oldEarned - (tonumber(q.Start) or 0))
					q.Goal = math.max(1, math.floor(q.Goal * f + 0.5))
					q.Start = d.SnowEarned - done * f
				end
			end
		end
	end
	if type(d.Contracts) == "table" and tonumber(d.Contracts.BonusSnow) then d.Contracts.BonusSnow = math.floor(M.Map(d.Contracts.BonusSnow) + 0.5) end
	local C = config
	local p = type(d.Plow) == "table" and d.Plow or nil
	if p and C and C.OfferPrice then
		if type(p.Offers) == "table" then for _, o in pairs(p.Offers) do if type(o) == "table" then o.Price = C.OfferPrice(o) end end end
		if type(p.Reserved) == "table" then p.Reserved.Price = C.OfferPrice(p.Reserved) end
	end
	d.EconomyVersion = M.VERSION
	d.EconomyMigrated = {From = 1, Snow = before.Snow, SnowEarned = before.SnowEarned, At = os.time()}
	return true
end
return M
'''

